"""Human approval gates for sensitive Phase 9 operations.







































































A Phase 9 approval is a *capability token* with the following binding:







































































* **operation scope** – an explicit operation name (``workspace.modify``,



































  ``provider.enable`` ...);



































* **target scope** – the exact target identity (workspace-relative path,



































  provider id, plan step id ...);



































* **payload binding** – a SHA-256 over the canonical payload, so a token



































  approved for one content cannot authorise different content;



































* **single use** – the token is consumed on first successful verification;



































* **expiry** – bounded TTL;



































* **no self-approval** – the requesting principal may not decide its own



































  request;



































* **explicit decision** – only an explicit ``approve``/``reject`` transition



































  counts; a missing or ambiguous decision is a rejection, never an implicit



































  approval.







































































The gate is deterministic and fully auditable; it performs no I/O of its own



































beyond the injected audit log.



































"""







































































